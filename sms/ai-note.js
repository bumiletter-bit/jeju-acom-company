// 엔진이 답 끝에 붙이는 꼬리 — 판정에는 방해가 안 되지만 text 에서는 뺀다(문자용 꼬리 제거는 sms-safe.js 가 한 번 더 한다)
const TAIL_RE = /\n*\*?\s*추가\s*문의\s*사항[^\n]*(톡톡|카카오톡|고객센터|010-?6687-?4031)[^\n]*\s*$/;

function parse(answerText) {
    let raw = String(answerText == null ? '' : answerText).replace(/\r\n?/g, '\n').trim();
    if (!raw) return { toStaff: true, text: '', why: '빈 답' };
    raw = raw.replace(/^사용시나리오\s*[:：][^\n]*\n?/, '').trim();          // 엔진 헤더가 남아 있으면 떼고 본다
    const body = raw.replace(TAIL_RE, '').trim();
    if (!body || /^SKIP\b/.test(body)) return { toStaff: true, text: '', why: 'SKIP' };
    const m = body.match(/^\s*[\[［【]\s*사람\s*[\]］】]\s*[:：\-–—]?\s*([^\n]*)/);
    if (m) return { toStaff: true, text: '', why: m[1].trim().slice(0, 60) || '사람 확인' };
    if (/[\[［【]\s*사람\s*[\]］】]/.test(body) || /SKIP/.test(body)) return { toStaff: true, text: '', why: '본문에 판정 문구 섞임' };
    return { toStaff: false, text: body, why: '' };
}

module.exports = { SMS_SYSTEM_NOTE, STAFF_TAG, parse };
